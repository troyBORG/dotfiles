'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = path.join(__dirname, '../plasmoid/FFXITimers');
const qml = fs.readFileSync(path.join(base, 'contents/ui/main.qml'), 'utf8');
const metadata = JSON.parse(fs.readFileSync(path.join(base, 'metadata.json'), 'utf8'));
test('Days tab is exclusive, snapshot-driven and uses existing formatting', () => {
    assert.match(qml, /text: "Days"\s+checkable: true\s+checked: root.selectedView === 3\s+onClicked: root.selectedView = 3/);
    assert.match(qml, /id: routeColumn\s+visible: root.selectedView === 1 \|\| root.selectedView === 2/);
    assert.ok(!qml.includes('visible: root.selectedView !== 0'));
    assert.match(qml, /root.selectedView === 3 \? daysColumn.implicitHeight : routeColumn.implicitHeight/);
    assert.match(qml, /id: daysColumn\s+visible: root.selectedView === 3/);
    assert.match(qml, /model: 10/);
    assert.match(qml, /property var dayInfo: root.timerData.upcomingDays\[index\]/);
    assert.ok(qml.includes('root.localDate(new Date(dayRow.dayInfo.startMs))'));
    assert.ok(qml.includes('"in " + FFXI.formatDuration(dayRow.dayInfo.countdownMs, true)'));
    assert.ok(qml.includes('text: "Next 10 day starts · local time"'));
    assert.match(qml, /property double firstDayStartMs: root.timerData.upcomingDays\[0\].startMs/);
    assert.match(qml, /onFirstDayStartMsChanged: \{\s+if \(root.selectedView === 3\) resetScroll\(\)/);
    assert.match(qml, /function onSelectedViewChanged\(\) \{ contentFlick.resetScroll\(\) \}/);
    assert.match(qml, /Qt.callLater\(function\(\) \{ contentFlick.contentY = 0 \}\)/);
    assert.equal((qml.match(/new XMLHttpRequest\(/g) || []).length, 1);
    assert.equal((qml.match(/\bTimer\s*\{/g) || []).length, 3);
    assert.ok(qml.includes('property var timerData: FFXI.snapshot(Date.now())'));
    assert.ok(qml.includes('text: root.timerData.vana.dayName + "  " + root.timerData.vana.calendar'));
    assert.ok(qml.includes('return Qt.formatDateTime(date, "ddd MMM d, h:mm AP")'));
    assert.equal(metadata.KPlugin.Id, 'com.pennywiseops.ffxitimers');
    assert.equal(metadata.KPackageStructure, 'Plasma/Applet');
    assert.equal(metadata['X-Plasma-API-Minimum-Version'], '6.0');
});
